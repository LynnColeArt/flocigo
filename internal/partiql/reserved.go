var reserved = func() map[string]bool {
	m := make(map[string]bool)
	for _, w := range strings.Fields(reservedWordsRaw) {
		m[w] = true
	}
	return m
}()

// isReserved reports whether an (already case-folded) word is a reserved
// attribute name.
func isReserved(w string) bool {
	return reserved[strings.ToUpper(w)]
}
